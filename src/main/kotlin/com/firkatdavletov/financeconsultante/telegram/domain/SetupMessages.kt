package com.firkatdavletov.financeconsultante.telegram.domain

internal object SetupMessages {
    fun pending(dialog: SetupDialog): String =
        if (dialog.step == SetupStep.IDLE) "" else "\nТекущий шаг: " + prompt(dialog.step)

    fun prompt(step: SetupStep): String =
        when (step) {
            SetupStep.OPENING -> {
                "Введите начальный остаток в KZT (до двух знаков после запятой; отрицательный " +
                    "допустим). /cancel — отмена."
            }

            SetupStep.DATE -> {
                "Введите дату начала учёта ГГГГ-ММ-ДД, не позже сегодня. Остаток относится к началу " +
                    "этого дня в Asia/Almaty. /cancel — отмена."
            }

            SetupStep.REPORT_TIME -> {
                "Введите время отчётов ЧЧ:ММ в Asia/Almaty (по умолчанию 08:00). Отправьте 08:00, " +
                    "чтобы сохранить его. /cancel — отмена."
            }

            SetupStep.RESERVE -> {
                "Введите денежный резерв в KZT, не меньше нуля. Резерв не является расходом. /cancel — отмена."
            }

            SetupStep.IDLE -> {
                MENU
            }
        }

    fun summary(current: BudgetSettings?): String =
        if (current == null) {
            "Бюджет ещё не настроен. KZT/RUB; основная KZT; Asia/Almaty; отчёт 08:00. /start"
        } else {
            "Валюты: KZT и RUB. Основная: KZT. Часовой пояс: Asia/Almaty.\n" +
                "Начальный остаток: ${current.openingBalance.amount.toPlainString()} KZT; дата: " +
                "${current.startedOn}.\n" +
                "Время отчётов: ${current.reportTime}. Резерв: ${current.cashReserve.amount.toPlainString()} KZT.\n" +
                "/today — дневной лимит; /forecast — прогноз на 30 дней; /report week|month — аналитика; " +
                "периодические отчёты отправляются при включённых уведомлениях."
        }

    const val MENU = "/opening — остаток и дата; /report_time — время отчётов; /reserve — резерв; /cancel — отмена."
    const val INTRO =
        "Бот учитывает введённые операции и не знает банковский остаток. " +
            "Валюты: KZT/RUB, основная KZT, Asia/Almaty, отчёт 08:00. Настроим бюджет."
    const val FIXED_SETTINGS =
        "В MVP основная валюта KZT и часовой пояс Asia/Almaty фиксированы. " +
            "Суммы существующих операций нельзя просто переименовать в другую валюту. RUB " +
            "учитывается по дневному курсу."
    const val HELP =
        "/start — начать или продолжить настройку; /settings — показать настройки. " + MENU +
            "\nФормат операций: продукты 15 000; аптека 700,50 RUB; зарплата 1300000. " +
            "Явный ввод: /expense <сумма> [валюта] <категория> или /income <сумма> [валюта] <категория>. " +
            "Например: /expense 700.50 RUB здоровье; /income 1300000 зарплата. " +
            "Расходы: продукты (супермаркет), здоровье (аптека); доходы: зарплата. " +
            "Без валюты — KZT; поддерживаются KZT/тенге/₸ и RUB/рубль/рубля/рубли/рублей/₽. " +
            "Дата необязательна: сегодня, вчера, ГГГГ-ММ-ДД или ДД.ММ.ГГГГ в конце операции. " +
            "Без даты — день отправки сообщения в Asia/Almaty. Одна операция в одной строке; максимум два " +
            "дробных знака. " +
            "Вопрос о покупке не создаёт расход: /purchase <сумма KZT> [дата] [нужно|хочу] " +
            "[goal=<UUID>] [daily=<KZT в день>] рассчитывает сценарий. " +
            "Однозначные операции записываются сразу. /balance — баланс; /today — дневной лимит и оценка; " +
            "/forecast [лимит KZT в день] — прогноз по датам на 30 дней; " +
            "/report week и /report month — аналитика текущего сопоставимого периода; " +
            "/history — последние 10 записей и следующая страница. " +
            "/draft [страница] — незавершённые черновики; /confirm — подтвердить единственный черновик; " +
            "/confirm <id> <версия> — резервная команда подтверждения. " +
            "AI-черновик можно подтвердить, отменить или выбрать категорию из grid; " +
            "подтверждённая фраза запоминается как правило. Готовые предложения не заменяют друг друга. " +
            "/cancel отменяет единственный черновик, при нескольких выберите нужный кнопкой. " +
            "Без курса RUB операция ожидает курс в черновике и требует подтверждения после загрузки. " +
            "Выберите запись кнопкой в /history или под подтверждением: сумма, категория, дата, " +
            "отмена и возврат. " +
            "Кнопки безопасно передают ID и версию. /cancel отменяет только черновик; " +
            "отмена проводки — отдельная кнопка. " +
            "/refund <id> <версия> <сумма> [ГГГГ-ММ-ДД] — возврат в исходной валюте. " +
            "/categories — экран категорий: просмотр, создание, переименование, иконка и безопасное удаление. " +
            "После исправления категории: /rule <id> <версия> <слово или фраза>; /rules — правила. " +
            "/recurring — постоянные платежи и конкретные обязательства; " +
            "/recurring analyze — поиск повторяющихся расходов с подтверждением; " +
            "/expected — ожидаемые доходы. " +
            "Плановые суммы задаются в KZT и сами по себе не меняют баланс; фактическая оплата или доход " +
            "создают связанную проводку только по явной команде. Уже записанный расход можно связать через " +
            "/recurring match с ID из выбранной записи /history. " +
            "/goals — цели, фактически выделенные накопления и отдельные будущие планы взносов. " +
            "Выделение и возврат денег цели не являются доходом или расходом; трата из цели записывается явно. " +
            "/family — роль, участники и права; OWNER приглашает и отзывает участников и настраивает отчёты. " +
            "MEMBER читает общий бюджет, добавляет операции и меняет только свои записи. " +
            "Редактирование исходного сообщения не меняет учёт. " +
            FIXED_SETTINGS
}
